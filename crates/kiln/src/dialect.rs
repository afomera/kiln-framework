//! Database backends: everything that differs between SQLite, Postgres and (later) MySQL.
//!
//! Kiln talks to every database through one handle ([`crate::Db`], on sqlx's `Any`
//! driver) and writes its SQL once, in a portable form: `?` placeholders, double-quoted
//! identifiers, and SQLite-style DDL for its own tables. A [`Dialect`] turns that into what
//! its backend expects, and answers the questions where backends genuinely differ (how
//! migrations change a column, how workers lock a job). Adding a backend means one more
//! `impl Dialect` and a sqlx driver feature; nothing else in Kiln changes.

use std::borrow::Cow;

use crate::{Error, Result, Value};

/// What Kiln needs to know about a database backend.
pub trait Dialect: Send + Sync + 'static {
    /// `sqlite`, `postgres`, `mysql`.
    fn name(&self) -> &'static str;

    /// Turns Kiln's `?` placeholders into the backend's and adjusts the binds to match.
    fn prepare<'a>(&self, sql: &'a str, binds: Vec<Value>) -> (Cow<'a, str>, Vec<Value>) {
        (Cow::Borrowed(sql), binds)
    }

    /// The column type for one of Kiln's logical types (`INTEGER`, `REAL`, `TEXT`).
    fn column_type(&self, logical: &str) -> String {
        logical.to_owned()
    }

    /// The definition of an auto-numbered `id` primary key.
    fn primary_key(&self, column: &str) -> String;

    /// Translates DDL written for Kiln's own tables (SQLite style) for this backend.
    fn ddl<'a>(&self, sql: &'a str) -> Cow<'a, str> {
        Cow::Borrowed(sql)
    }

    /// A query returning the names of `table`'s columns.
    fn columns_query(&self, table: &str) -> String;

    /// Appended to the subquery that picks the next job, to lock it.
    fn claim_lock(&self) -> &'static str {
        ""
    }

    /// Run inside the claim's transaction first, when concurrent claims must queue
    /// (so per-queue limits hold across workers). `None` when the backend serializes
    /// writes anyway.
    fn serialize_claims(&self) -> Option<&'static str> {
        None
    }

    /// Run on every new connection.
    fn on_connect(&self) -> Option<&'static str> {
        None
    }

    /// Whether a column's type, nullability or constraints can be changed with ALTER
    /// TABLE. When not (SQLite), migrations rebuild the table.
    fn alters_columns(&self) -> bool;
}

/// SQLite: the default for development and single-node apps.
pub struct Sqlite;

/// Postgres.
pub struct Postgres;

impl Dialect for Sqlite {
    fn name(&self) -> &'static str {
        "sqlite"
    }

    fn primary_key(&self, column: &str) -> String {
        format!("\"{column}\" INTEGER PRIMARY KEY AUTOINCREMENT")
    }

    fn columns_query(&self, table: &str) -> String {
        format!("SELECT \"name\" FROM pragma_table_info('{}')", table.replace('\'', "''"))
    }

    fn alters_columns(&self) -> bool {
        false
    }
}

impl Dialect for Postgres {
    fn name(&self) -> &'static str {
        "postgres"
    }

    /// `?` → `$1, $2, ..`, skipping quoted strings and identifiers. NULL binds are written
    /// into the SQL as `NULL`: Postgres types every parameter, and a NULL has no type of its
    /// own, while a literal NULL fits any column.
    fn prepare<'a>(&self, sql: &'a str, binds: Vec<Value>) -> (Cow<'a, str>, Vec<Value>) {
        if !sql.contains('?') {
            return (Cow::Borrowed(sql), binds);
        }
        let mut out = String::with_capacity(sql.len() + 16);
        let mut kept = Vec::with_capacity(binds.len());
        let mut binds = binds.into_iter();
        let mut quote: Option<char> = None;
        for c in sql.chars() {
            match (quote, c) {
                (Some(q), c) if c == q => {
                    quote = None;
                    out.push(c);
                }
                (Some(_), c) => out.push(c),
                (None, '\'' | '"') => {
                    quote = Some(c);
                    out.push(c);
                }
                (None, '?') => match binds.next() {
                    Some(Value::Null) | None => out.push_str("NULL"),
                    Some(value) => {
                        kept.push(value);
                        out.push('$');
                        out.push_str(&kept.len().to_string());
                    }
                },
                (None, c) => out.push(c),
            }
        }
        (Cow::Owned(out), kept)
    }

    fn column_type(&self, logical: &str) -> String {
        match logical {
            "INTEGER" => "BIGINT".to_owned(),
            "REAL" => "DOUBLE PRECISION".to_owned(),
            other => other.to_owned(),
        }
    }

    fn primary_key(&self, column: &str) -> String {
        format!("\"{column}\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    }

    fn ddl<'a>(&self, sql: &'a str) -> Cow<'a, str> {
        let sql =
            sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
        Cow::Owned(replace_word(&sql, "INTEGER", "BIGINT").replace(" REAL", " DOUBLE PRECISION"))
    }

    fn columns_query(&self, table: &str) -> String {
        format!(
            "SELECT CAST(\"column_name\" AS TEXT) FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '{}'",
            table.replace('\'', "''")
        )
    }

    /// Kiln creates its tables with `IF NOT EXISTS`; the "already exists, skipping"
    /// notices that causes are noise.
    fn on_connect(&self) -> Option<&'static str> {
        Some("SET client_min_messages TO warning")
    }

    fn claim_lock(&self) -> &'static str {
        " FOR UPDATE SKIP LOCKED"
    }

    fn serialize_claims(&self) -> Option<&'static str> {
        // One lock for all claims in the database: they're quick, and it's what makes
        // `app.queue_limit(..)` exact under concurrency.
        // (Wrapped so no `void` column comes back.)
        Some("SELECT 1 FROM (SELECT pg_advisory_xact_lock(7361001)) AS \"claim_lock\"")
    }

    fn alters_columns(&self) -> bool {
        true
    }
}

/// Replaces `word` where it stands alone (not inside another word).
fn replace_word(text: &str, word: &str, with: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find(word) {
        let before = rest[..at].chars().last();
        let after = rest[at + word.len()..].chars().next();
        let boundary = |c: Option<char>| c.is_none_or(|c| !c.is_ascii_alphanumeric() && c != '_');
        out.push_str(&rest[..at]);
        out.push_str(if boundary(before) && boundary(after) { with } else { word });
        rest = &rest[at + word.len()..];
    }
    out.push_str(rest);
    out
}

/// The dialect for a database URL.
pub fn for_url(url: &str) -> Result<&'static dyn Dialect> {
    let scheme = url.split(':').next().unwrap_or_default();
    match scheme {
        "sqlite" => Ok(&Sqlite),
        "postgres" | "postgresql" => Ok(&Postgres),
        "mysql" | "mariadb" => Err(Error::Config("MySQL isn't supported yet (it's planned: see kiln::dialect)".into())),
        other => Err(Error::Config(format!("`{other}:` isn't a database Kiln knows; use sqlite:// or postgres://"))),
    }
}

/// The dialect a snapshot's `backend` field names.
pub fn named(name: &str) -> Option<&'static dyn Dialect> {
    match name {
        "sqlite" => Some(&Sqlite),
        "postgres" => Some(&Postgres),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn postgres_numbers_placeholders_and_inlines_nulls() {
        let (sql, binds) = Postgres.prepare(
            "UPDATE \"t\" SET \"a\" = ?, \"b\" = ?, \"note\" = 'what?' WHERE \"id\" = ? AND \"x?\" = ?",
            vec![Value::Integer(1), Value::Null, Value::Text("t".into()), Value::Integer(9)],
        );
        assert_eq!(
            sql,
            "UPDATE \"t\" SET \"a\" = $1, \"b\" = NULL, \"note\" = 'what?' WHERE \"id\" = $2 AND \"x?\" = $3"
        );
        assert_eq!(binds, vec![Value::Integer(1), Value::Text("t".into()), Value::Integer(9)]);
    }

    #[test]
    fn postgres_translates_kiln_ddl() {
        let ddl = Postgres.ddl("CREATE TABLE \"k\" (\"id\" INTEGER PRIMARY KEY AUTOINCREMENT, \"n\" INTEGER NOT NULL, \"t\" TEXT, \"r\" REAL, \"xINTEGERy\" TEXT)");
        assert_eq!(
            ddl,
            "CREATE TABLE \"k\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"n\" BIGINT NOT NULL, \"t\" TEXT, \"r\" DOUBLE PRECISION, \"xINTEGERy\" TEXT)"
        );
    }

    #[test]
    fn urls_pick_dialects() {
        assert_eq!(for_url("sqlite://db.sqlite3").unwrap().name(), "sqlite");
        assert_eq!(for_url("postgres://localhost/app").unwrap().name(), "postgres");
        assert!(for_url("mysql://localhost/app").is_err());
    }
}
